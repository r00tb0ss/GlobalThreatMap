"""Build requirements/requirements.lock (and optionally a wheelhouse) for every supported target.

Targets: CPython 3.11, 3.12, 3.13 x manylinux x86_64 / aarch64. Uses `pip download --only-binary`
so the lock only contains packages that have prebuilt wheels for ARM64 (no compiler needed on a Pi).

usage: python scripts/lock_requirements.py [--wheelhouse DIR]
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
PYTHONS = ["311", "312", "313"]
PLATFORMS = {"x86_64": "manylinux2014_x86_64", "aarch64": "manylinux2014_aarch64"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wheelhouse", help="also keep every downloaded wheel here (offline bundle)")
    a = ap.parse_args()
    req_in = os.path.join(ROOT, "requirements", "requirements.in")
    base = a.wheelhouse or tempfile.mkdtemp(prefix="gti-wheels-")
    pk = {}
    for py in PYTHONS:
        for arch, plat in PLATFORMS.items():
            d = os.path.join(base, f"cp{py}-{arch}")
            subprocess.run([sys.executable, "-m", "pip", "download", "-q", "--disable-pip-version-check",
                            "-r", req_in, "--only-binary=:all:", "--platform", plat, "--python-version", py,
                            "--implementation", "cp", "-d", d], check=True)
            for f in os.listdir(d):
                m = re.match(r"^([A-Za-z0-9_.]+)-([0-9][^-]*)-", f)
                if not m:
                    raise SystemExit(f"unexpected file {f}")
                key = (m.group(1).lower().replace("_", "-"), m.group(2))
                with open(os.path.join(d, f), "rb") as fh:
                    pk.setdefault(key, set()).add(hashlib.sha256(fh.read()).hexdigest())
    versions = {}
    for n, v in pk:
        versions.setdefault(n, set()).add(v)
    bad = {n: v for n, v in versions.items() if len(v) > 1}
    if bad:
        raise SystemExit(f"inconsistent versions across targets: {bad}")
    out = os.path.join(ROOT, "requirements", "requirements.lock")
    lines = ["# Generated by scripts/lock_requirements.py from requirements.in. Do not edit by hand.",
             "# Hashes cover CPython 3.11-3.13 wheels for manylinux x86_64 and aarch64 (Raspberry Pi 4/5).",
             "# Installed with: pip install --require-hashes --only-binary=:all: -r requirements.lock"]
    for n, v in sorted(pk):
        lines.append(f"{n}=={v} \\")
        hs = sorted(pk[(n, v)])
        for i, h in enumerate(hs):
            lines.append(f"    --hash=sha256:{h}" + (" \\" if i < len(hs) - 1 else ""))
    with open(out, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(pk)} packages, {sum(len(x) for x in pk.values())} hashes -> {out}")


if __name__ == "__main__":
    main()
